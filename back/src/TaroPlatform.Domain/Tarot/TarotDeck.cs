namespace TaroPlatform.Domain.Tarot;

/// <summary>
/// Фабрика колоди (патерн Factory). Колода будується один раз при першому зверненні.
/// Ідентифікатори: 0–21 старші аркани, 22–77 молодші.
/// </summary>
public static class TarotDeck
{
    private static readonly Lazy<IReadOnlyList<TarotCard>> Cards = new(Build);

    public static IReadOnlyList<TarotCard> All => Cards.Value;

    public static TarotCard GetById(int id) => Cards.Value.Single(c => c.Id == id);

    private static IReadOnlyList<TarotCard> Build()
    {
        var list = new List<TarotCard>();

        for (var i = 0; i < MajorData.Length; i++)
        {
            var (name, up, rev) = MajorData[i];
            list.Add(new MajorArcana(i, name, up, rev));
        }

        for (var s = 0; s < Suits.Length; s++)
        {
            var (suit, suitName, suitTheme) = Suits[s];
            for (var r = 0; r < Ranks.Length; r++)
            {
                var (rank, rankMeaning) = Ranks[r];
                var id = MajorData.Length + s * Ranks.Length + r;
                list.Add(new MinorArcana(
                    id,
                    suit,
                    $"{rank} {suitName}",
                    $"{rankMeaning}: {suitTheme}.",
                    $"{rankMeaning}, але блокується або викривлюється: {suitTheme} потребує уваги."));
            }
        }

        return list;
    }

